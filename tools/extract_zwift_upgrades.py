"""Export versioned bike upgrade definitions from global.wad.

Usage: python tools\\extract_zwift_upgrades.py [--zwift-dir PATH] [--out zwiftdata]
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from bike_comparison.upgrades import validate_definition
from tools.extract_zwift_bikes import read_zwift_version
from tools.extract_zwift_routes import read_wad_entries

CONFIG_ENTRY = "bikes/levels/config.json"


def extract_upgrades(zwift_dir: str, out: str) -> dict:
    version = read_zwift_version(zwift_dir)
    if not version:
        raise ValueError(f"Could not read installed Zwift version from {zwift_dir}")
    entries = read_wad_entries(
        str(Path(zwift_dir) / "assets" / "global.wad"), keep_substrings=("bikes/levels/",),
    )
    if CONFIG_ENTRY not in entries:
        raise ValueError(f"Missing {CONFIG_ENTRY} in global.wad")
    config = json.loads(entries[CONFIG_ENTRY])
    if (not isinstance(config, dict) or config.get("type") != "bike_levels_config"
            or not isinstance(config.get("levelup_configs"), list) or not config["levelup_configs"]):
        raise ValueError("Invalid bike levels configuration")
    definitions = {}
    for filename in config["levelup_configs"]:
        if not isinstance(filename, str) or not filename:
            raise ValueError(f"Invalid upgrade definition filename: {filename}")
        source = f"bikes/levels/{filename}"
        if source not in entries:
            raise ValueError(f"Missing upgrade definition: {source}")
        definition = json.loads(entries[source])
        validate_definition(definition)
        identifier = definition["id"]
        if identifier in definitions:
            raise ValueError(f"Duplicate upgrade definition: {identifier}")
        definitions[identifier] = definition
    export = {
        "_comment": "Auto-generated by tools/extract_zwift_upgrades.py; do not edit by hand.",
        "zwift_version": version,
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "source": "global.wad:bikes/levels/",
        "config": config,
        "levelup_configs": dict(sorted(definitions.items())),
    }
    payload = json.dumps(export, ensure_ascii=True, indent=1, allow_nan=False) + "\n"
    destination = Path(out)
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "game_upgrades.json").write_text(payload, encoding="utf-8")
    return export


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zwift-dir", default=r"C:\Program Files (x86)\Zwift")
    parser.add_argument("--out", default="zwiftdata")
    args = parser.parse_args()
    export = extract_upgrades(args.zwift_dir, args.out)
    print(f"Exported {len(export['levelup_configs'])} upgrade definitions for "
          f"{export['zwift_version']}")


if __name__ == "__main__":
    main()
