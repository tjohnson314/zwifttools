"""Export verified entitlement mappings and unresolved reward-spinner IDs.

Usage: python tools\\extract_zwift_entitlements.py [--zwift-dir PATH]
       [--out zwiftdata]
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.extract_zwift_bikes import read_zwift_version
from tools.extract_zwift_routes import load_multiroot, read_wad_entries

REGISTRY_ENTRY = "Entitlements/entitlements.json"
SPINNER_ENTRY = "RewardSpinners/RewardSpinners.xml"


def parse_registry(data: bytes) -> tuple[dict, dict[str, dict], list[int]]:
    registry = json.loads(data)
    if not isinstance(registry, dict) or registry.get("type") != "entitlements":
        raise ValueError("Invalid entitlement registry")
    records = registry.get("entitlements")
    if not isinstance(records, list) or not records:
        raise ValueError("Entitlement registry has no records")
    by_id = {}
    invalid_paths = []
    for record in records:
        if not isinstance(record, dict):
            raise ValueError("Invalid entitlement record")
        identifier = record.get("entitlementId")
        if type(identifier) is not int or identifier < 0:
            raise ValueError(f"Invalid entitlement ID: {identifier!r}")
        key = str(identifier)
        if key in by_id:
            raise ValueError(f"Duplicate entitlement ID: {identifier}")
        for field in ("shortName", "category"):
            if not isinstance(record.get(field), str) or not record[field].strip():
                raise ValueError(f"Entitlement {identifier} has invalid {field}")
        paths = record.get("associatedPaths")
        if not isinstance(paths, list):
            raise ValueError(f"Entitlement {identifier} has invalid associatedPaths")
        if not paths or any(not isinstance(path, str) or not path.strip() for path in paths):
            invalid_paths.append(identifier)
        by_id[key] = record
    metadata = {key: value for key, value in registry.items() if key != "entitlements"}
    return metadata, dict(sorted(by_id.items(), key=lambda item: int(item[0]))), sorted(invalid_paths)


def parse_spinner_ids(data: bytes) -> set[int]:
    root = load_multiroot(data)
    if root.find("SpinnerDefinitions") is None:
        raise ValueError("Missing reward-spinner definitions")
    identifiers = set()
    for prize in root.iter("Prize"):
        value = prize.get("entitlement")
        if value is None or value == "ENTITLEMENT_NONE":
            continue
        if re.fullmatch(r"[0-9]+", value) is None:
            raise ValueError(f"Unsupported spinner entitlement reference: {value!r}")
        identifiers.add(int(value))
    return identifiers


def extract_entitlements(zwift_dir: str, out: str) -> dict:
    version = read_zwift_version(zwift_dir)
    if not version:
        raise ValueError(f"Could not read installed Zwift version from {zwift_dir}")
    assets = Path(zwift_dir) / "assets"
    registry_entries = read_wad_entries(
        str(assets / "globalproj.wad"), keep_substrings=(REGISTRY_ENTRY,),
    )
    spinner_entries = read_wad_entries(
        str(assets / "global.wad"), keep_substrings=(SPINNER_ENTRY,),
    )
    if REGISTRY_ENTRY not in registry_entries:
        raise ValueError(f"Missing {REGISTRY_ENTRY} in globalproj.wad")
    if SPINNER_ENTRY not in spinner_entries:
        raise ValueError(f"Missing {SPINNER_ENTRY} in global.wad")
    metadata, entitlements, invalid_paths = parse_registry(registry_entries[REGISTRY_ENTRY])
    referenced_ids = parse_spinner_ids(spinner_entries[SPINNER_ENTRY])
    export = {
        "_comment": "Auto-generated by tools/extract_zwift_entitlements.py; do not edit by hand.",
        "zwift_version": version,
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "coverage": "packaged_registry_only",
        "source": f"globalproj.wad:{REGISTRY_ENTRY}",
        "registry_metadata": metadata,
        "entitlements": entitlements,
        "reference_source": f"global.wad:{SPINNER_ENTRY}",
        "unresolved_entitlement_ids": sorted(referenced_ids - {int(key) for key in entitlements}),
        "invalid_associated_path_ids": invalid_paths,
    }
    payload = json.dumps(export, ensure_ascii=True, indent=1, allow_nan=False) + "\n"
    destination = Path(out)
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "game_entitlements.json").write_text(payload, encoding="utf-8")
    if invalid_paths:
        print(f"warning: entitlement records with invalid associated paths retained: "
              f"{', '.join(map(str, invalid_paths))}", file=sys.stderr)
    return export


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zwift-dir", default=r"C:\Program Files (x86)\Zwift")
    parser.add_argument("--out", default="zwiftdata")
    args = parser.parse_args()
    export = extract_entitlements(args.zwift_dir, args.out)
    print(f"Exported {len(export['entitlements'])} verified registry mappings for "
          f"{export['zwift_version']}; "
          f"{len(export['unresolved_entitlement_ids'])} unresolved spinner IDs")


if __name__ == "__main__":
    main()
